import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { buildApp } from '../shared/build-app.mjs';
// The Launch page fills in and hands out the same server setup script that is in the repository.
writeFileSync('src/setup-script.js', '// Generated by build.mjs from rivers-testnet/validator-setup.sh. Do not edit.\nconst RV_SETUP_SCRIPT=' + JSON.stringify(readFileSync('../../rivers-testnet/validator-setup.sh', 'utf8')) + ';\n');
await buildApp(import.meta.url, { app: 'validator', name: 'Rivers Validator', views: ['src/setup-script.js', 'src/live-validator.js'], build });
